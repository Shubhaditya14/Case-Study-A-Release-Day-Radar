"""
Step 09 — Load the clean tables into MySQL, then run every query in sql/queries.sql.

  1. (Re)create the schema from sql/schema.sql — keys and foreign keys included.
  2. Insert films FIRST (the other tables point to it), then trailers, box_office, comments, trends_daily.
  3. Run each query in sql/queries.sql and save its result to outputs/tables/sql_q<n>.csv,
     plus one markdown file with every query and its output for the report appendix.

Needs the MySQL container running (docker start radar-mysql) and MYSQL_* in .env.
"""

import os
import re
import sys

import pandas as pd
from sqlalchemy import create_engine, text

sys.path.insert(0, os.path.dirname(__file__))
from utils import DATA_CLEAN, OUT_TABLES, ROOT, get_env  # noqa: E402

LOAD_ORDER = ["films", "trailers", "box_office", "comments", "trends_daily"]


def engine():
    url = (f"mysql+pymysql://{get_env('MYSQL_USER')}:{get_env('MYSQL_PASSWORD')}"
           f"@{get_env('MYSQL_HOST')}:{get_env('MYSQL_PORT')}/{get_env('MYSQL_DB')}?charset=utf8mb4")
    return create_engine(url)


def sql_statements(path):
    """Split a .sql file into statements. Comment lines are removed first, so a ';' in a comment is harmless."""
    lines = [line for line in path.read_text().splitlines() if not line.strip().startswith("--")]
    return [s.strip() for s in "\n".join(lines).split(";") if s.strip()]


def query_titles(path):
    """The '-- Qn. ...' comment above each query, used as its title in the results file."""
    titles, current = [], []
    for line in path.read_text().splitlines():
        if line.startswith("-- Q"):
            current = [line[3:].strip()]
        elif line.startswith("--") and current:
            current.append(line[2:].strip())
        elif line.strip() and current:
            titles.append(" ".join(current))
            current = []
    return titles


def load_tables(eng):
    with eng.begin() as conn:
        for statement in sql_statements(ROOT / "sql" / "schema.sql"):
            conn.execute(text(statement))

    tables = {name: pd.read_csv(DATA_CLEAN / f"{name}.csv") for name in LOAD_ORDER}
    # Columns in the CSVs that are not in the schema (e.g. like_count) are left out on purpose
    tables["comments"] = tables["comments"][["comment_id", "film_id", "published_ts", "text_clean", "length", "vader_compound"]]
    tables["trailers"] = tables["trailers"][["film_id", "youtube_video_id", "is_main_trailer", "publish_ts", "views", "likes", "comment_count"]]

    counts = []
    for name in LOAD_ORDER:
        df = tables[name]
        # chunksize keeps each INSERT small enough for MySQL's packet limit (comments are 350k rows)
        df.to_sql(name, eng, if_exists="append", index=False, chunksize=5000, method="multi")
        counts.append({"table": name, "rows_loaded": len(df)})
        print(f"loaded {name:<13} {len(df):>9,} rows")
    pd.DataFrame(counts).to_csv(OUT_TABLES / "mysql_row_counts.csv", index=False)


def run_queries(eng):
    path = ROOT / "sql" / "queries.sql"
    statements = sql_statements(path)
    titles = query_titles(path)
    md = ["# SQL queries and their outputs", "", "Generated by `src/09_load_mysql.py` from `sql/queries.sql`.", ""]
    with eng.connect() as conn:
        for i, (statement, title) in enumerate(zip(statements, titles), start=1):
            result = pd.read_sql(text(statement), conn)
            result.to_csv(OUT_TABLES / f"sql_q{i}.csv", index=False)
            md += [f"## {title}", "", "```sql", statement, "```", "", result.to_markdown(index=False), ""]
            print(f"\nQ{i}: {title[:90]}\n{result.to_string(index=False)}")
    (OUT_TABLES / "sql_query_results.md").write_text("\n".join(md))


def main():
    eng = engine()
    load_tables(eng)
    run_queries(eng)


if __name__ == "__main__":
    main()
